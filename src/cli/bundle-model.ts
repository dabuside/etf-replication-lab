/**
 * Bundles the pure model layer (types + domain + model) into one classic
 * browser script with zero imports, so dist/index.html stays dependency-free.
 *
 * Uses the TypeScript compiler API only as a transpiler: each file is stripped
 * to JS, internal imports are dropped (everything lands in one scope), and the
 * public surface is pinned on globalThis.EtfLab. Nothing here executes the
 * model; it only packages it.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { bundleClassicScript, syntaxCheckScript } from './transpile.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'web', 'vendor', 'model.bundle.js');

const SOURCES = [
  'src/types.ts',
  'src/domain/tax.ts',
  'src/domain/ipo.ts',
  'src/domain/portfolio.ts',
  'src/model.ts',
];

const EXPORTS = [
  'compute',
  'computeIpo',
  'tradingCostPct',
  'ipoSample',
  'buildPortfolio',
  'exchangeSplit',
  'methodRequiredCount',
  'namesToReachWeight',
  'ticketsFromMarketValue',
  'expectedWins',
  'expectedWinsDetailed',
  'profitPerWin',
  'expectedProfit',
  'winningRate',
  'effectiveDividendTaxRate',
  'personalLongTermRate',
  'impliedTaxRate',
  'METHOD_LABELS',
  'ALL_METHODS',
  'MARKET_VALUE_PER_TICKET',
  'TAX_BANDS',
  'ETF_TAX_BOUNDS',
  'ASSUMPTIONS',
];

async function main(): Promise<void> {
  const bundle = await bundleClassicScript(ROOT, SOURCES, {
    header: '// Generated by src/cli/bundle-model.ts. Do not edit by hand.',
    footer: `globalThis.EtfLab = { ${EXPORTS.join(', ')} };`,
  });

  await syntaxCheckScript(bundle, 'model');
  await mkdir(dirname(OUT), { recursive: true });
  await writeFile(OUT, bundle, 'utf8');
  console.log(`wrote web/vendor/model.bundle.js (${(bundle.length / 1024).toFixed(1)} KB)`);
  console.log('bundle parses cleanly');
}

await main();
